            <h2>1. Who we are</h2>
            <p>The GLC AI Platform is operated by Greats Language Center, Kuala Lumpur, Malaysia. It provides AI-assisted English placement testing and a curriculum-based AI tutor for GLC students.</p>

            <h2>2. What we collect</h2>
            <ul>
                <li><strong>Account data:</strong> name, email address, and (for students) age band provided by GLC staff when your account or access code is created.</li>
                <li><strong>Guardian data (students aged 12-17):</strong> guardian name and email, used solely to record parental consent as required for minors.</li>
                <li><strong>Placement test data:</strong> your answers, writing and speaking responses, scores, and test-session events (such as tab switches) recorded for assessment integrity.</li>
                <li><strong>Tutor data:</strong> your conversation messages with the AI tutor and writing practice submissions, retained so teachers can support your learning.</li>
            </ul>

            <h2>3. How we use your data</h2>
            <ul>
                <li>To determine and communicate your placement level (reviewed and approved by GLC staff - results are never sent without human review).</li>
                <li>To provide tutoring grounded in GLC curriculum materials and let your assigned teacher review your practice history.</li>
                <li>To keep the platform safe, including audit logs of administrative actions.</li>
            </ul>
            <p>Test responses and tutor messages are processed by Google Gemini AI services to generate draft evaluations and tutor replies. AI outputs that affect your results are always reviewed by GLC staff before release.</p>

            <h2>4. Disclosure</h2>
            <p>We do not sell personal data. Data is visible only to authorised GLC staff (admins, academic supervisors, and your assigned teachers) and to our AI processing provider as described above.</p>

            <h2>5. Retention and your rights</h2>
            <p>Data is retained while you remain a GLC candidate or student and for a reasonable period afterwards as required by GLC's academic records policy. Under the Personal Data Protection Act 2010 (Malaysia), you may request access to or correction of your personal data by contacting GLC.</p>

            <h2>6. Contact</h2>
            <p>For privacy questions or PDPA requests, contact Greats Language Center administration.</p>
